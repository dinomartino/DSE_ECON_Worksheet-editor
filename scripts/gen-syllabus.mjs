#!/usr/bin/env node
/**
 * Writes `src/syllabus/hkdse2025.data.ts` from `docs/research/syllabus-2025.json` (k-0317).
 *
 * The app needs only names, codes, lesson hours and the guide's "NOT required" limits; the
 * page references, details and topics.ts notes stay in the research file. Run it after any
 * change to the JSON: `node scripts/gen-syllabus.mjs`. `src/syllabus/syllabus.test.ts`
 * fails when the module and the JSON disagree.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const SOURCE = join(ROOT, 'docs/research/syllabus-2025.json');
export const TARGET = join(ROOT, 'src/syllabus/hkdse2025.data.ts');

/** The slim tree the app reads. */
export function buildSyllabusData(json) {
  return {
    id: 'hkdse-econ-2025',
    hours: { compulsory: json.timeAllocation.compulsorySum, elective: json.timeAllocation.electiveEither },
    topics: json.topics.map((topic) => ({
      code: topic.code,
      part: topic.part,
      en: topic.en,
      zh: topic.zh,
      hours: topic.hours,
      keyPoints: topic.keyPoints.map((kp) => ({
        code: kp.code,
        en: kp.en,
        zh: kp.zh,
        notRequired: kp.notRequired,
        points: kp.points.map((p) => ({ code: p.code, en: p.en, zh: p.zh })),
      })),
    })),
  };
}

export function renderModule(data) {
  return `// Generated by scripts/gen-syllabus.mjs from docs/research/syllabus-2025.json. Do not edit by hand.
import type { SyllabusData } from './types';

export const HKDSE_ECON_2025: SyllabusData = ${JSON.stringify(data, null, 2)};
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const data = buildSyllabusData(JSON.parse(readFileSync(SOURCE, 'utf8')));
  writeFileSync(TARGET, renderModule(data));
  console.log(`wrote ${TARGET}`);
}
